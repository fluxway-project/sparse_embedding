"""Reference vectors generator using C++ native partitioner."""

from __future__ import annotations

from collections.abc import Mapping, Sequence

import numpy as np

import sparse_embedding


def generate_reference_vectors(
    assignment_name: str,
    key_dtype: str,
    partition_count: int,
    parameters: Mapping[str, object] | None = None,
    *,
    sample_keys: Sequence[int] | None = None,
) -> tuple[np.ndarray, np.ndarray]:
    """Generate reference keys and their shard assignment ranks using native partitioner.
    The partitioner used in actual distributed systems and when reading sparse embeddings may not be consistent.
    Thus, the typical values generated by this function can be used for verification.
    """
    if partition_count <= 0:
        raise ValueError("partition_count must be > 0")

    np_dtype = np.dtype(key_dtype)
    if sample_keys is None:
        if np.issubdtype(np_dtype, np.signedinteger):
            keys_list = [
                -(1 << 30),
                -1048576,
                -1024,
                -3,
                -2,
                -1,
                0,
                1,
                2,
                3,
                1024,
                1048576,
                (1 << 30) - 1,
            ]
        else:
            keys_list = [
                0,
                1,
                2,
                3,
                1024,
                1048576,
                (1 << 30) - 1,
                (1 << 31) - 1,
            ]
        keys_arr = np.array(keys_list, dtype=np_dtype)
    else:
        keys_arr = np.array(sample_keys, dtype=np_dtype)

    params = {str(k): str(v) for k, v in parameters.items()} if parameters else {}
    partitioner = sparse_embedding.create_partitioner(
        assignment_name, partition_count, params
    )
    ranks_dlpack = partitioner.partition(keys_arr)
    ranks_arr = np.from_dlpack(ranks_dlpack)

    return keys_arr, ranks_arr
